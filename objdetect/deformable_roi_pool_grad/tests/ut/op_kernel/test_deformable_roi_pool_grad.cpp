TEST_F(DeformableRoiPoolGradTest, test_case_with_offset_fp32)
{
    // byte sizes
    size_t gradByteSize = N * C * PH * PW * sizeof(float);
    size_t xByteSize = B * C * FEAT_H * FEAT_W * sizeof(float);
    size_t roisByteSize = N * 5 * sizeof(float);
    size_t offsetByteSize = N * 2 * PH * PW * sizeof(float);
    size_t gradXByteSize = B * C * FEAT_H * FEAT_W * sizeof(float);
    size_t gradOffsetByteSize = N * 2 * PH * PW * sizeof(float);
    size_t tiling_data_size = sizeof(DeformableRoiPoolGradTilingData);

    // 生成测试数据
    ASSERT_EQ(system("cd ./deformable_roi_pool_grad_data/ && python3 gen_data.py '(2, 4, 3, 3)' 'float32'"), 0);

    // 读入输入
    std::string gradFile = "./deformable_roi_pool_grad_data/float32_input_grad.bin";
    std::string xFile = "./deformable_roi_pool_grad_data/float32_input_x.bin";
    std::string roisFile = "./deformable_roi_pool_grad_data/float32_input_rois.bin";
    std::string offsetFile = "./deformable_roi_pool_grad_data/float32_input_offset.bin";

    uint8_t* grad = (uint8_t*)AscendC::GmAlloc(gradByteSize);
    ASSERT_NE(grad, nullptr);
    ASSERT_TRUE(ReadFile(gradFile, gradByteSize, grad, gradByteSize)) << "Failed to read grad file";
    uint8_t* x = (uint8_t*)AscendC::GmAlloc(xByteSize);
    ASSERT_NE(x, nullptr);
    ASSERT_TRUE(ReadFile(xFile, xByteSize, x, xByteSize)) << "Failed to read x file";
    uint8_t* rois = (uint8_t*)AscendC::GmAlloc(roisByteSize);
    ASSERT_NE(rois, nullptr);
    ASSERT_TRUE(ReadFile(roisFile, roisByteSize, rois, roisByteSize)) << "Failed to read rois file";
    uint8_t* offset = (uint8_t*)AscendC::GmAlloc(offsetByteSize);
    ASSERT_NE(offset, nullptr);
    ASSERT_TRUE(ReadFile(offsetFile, offsetByteSize, offset, offsetByteSize)) << "Failed to read offset file";

    // 输出
    uint8_t* gradX = (uint8_t*)AscendC::GmAlloc(gradXByteSize);
    ASSERT_NE(gradX, nullptr);
    uint8_t* gradOffset = (uint8_t*)AscendC::GmAlloc(gradOffsetByteSize);
    ASSERT_NE(gradOffset, nullptr);

    // Tiling 计算（参照 op_host tiling 实现）
    int64_t totalElements = (int64_t)N * C * PH * PW;
    int32_t needCoreNum = 1; // CPU 仿真固定 1 核
    int64_t typeSize = sizeof(float);
    int64_t gradInputPerCoreElems = (int64_t)B * C * FEAT_H * FEAT_W;
    int64_t wsGradInputStride = ((gradInputPerCoreElems * typeSize + 127) / 128) * 128 / typeSize;
    int64_t gradOffsetPerCoreElems = (int64_t)N * 2 * PH * PW;
    int64_t wsGradOffsetStride = ((gradOffsetPerCoreElems * typeSize + 127) / 128) * 128 / typeSize;
    int64_t wsGradInputBaseElems = ((needCoreNum * wsGradInputStride * typeSize + 127) / 128) * 128 / typeSize;

    // workspace = per-core buffer（float 类型）
    size_t workspaceSize = (size_t)(wsGradInputBaseElems * typeSize + wsGradOffsetStride * typeSize * needCoreNum);
    // 多预留一些避免 CPU 仿真 OOB
    workspaceSize = std::max(workspaceSize, (size_t)(gradXByteSize + gradOffsetByteSize + 1024));
    uint8_t* workspace = (uint8_t*)AscendC::GmAlloc(workspaceSize);
    ASSERT_NE(workspace, nullptr);

    uint8_t* tiling = (uint8_t*)AscendC::GmAlloc(tiling_data_size);
    ASSERT_NE(tiling, nullptr);

    // 填充 TilingData
    DeformableRoiPoolGradTilingData* tilingDatafromBin = reinterpret_cast<DeformableRoiPoolGradTilingData*>(tiling);
    memset(tilingDatafromBin, 0, tiling_data_size);
    tilingDatafromBin->needCoreNum = needCoreNum;
    tilingDatafromBin->N = N;
    tilingDatafromBin->C = C;
    tilingDatafromBin->pooledHeight = PH;
    tilingDatafromBin->pooledWidth = PW;
    tilingDatafromBin->B = B;
    tilingDatafromBin->H = FEAT_H;
    tilingDatafromBin->W = FEAT_W;
    tilingDatafromBin->samplingRatio = SAMPLING_RATIO;
    tilingDatafromBin->hasOffset = 1;
    tilingDatafromBin->spatialScale = SPATIAL_SCALE;
    tilingDatafromBin->gamma = GAMMA;
    tilingDatafromBin->totalElements = totalElements;
    tilingDatafromBin->gradInputElemNum = (int64_t)B * C * FEAT_H * FEAT_W;
    tilingDatafromBin->gradOffsetElemNum = (int64_t)N * 2 * PH * PW;
    tilingDatafromBin->wsGradInputStride = wsGradInputStride;
    tilingDatafromBin->wsGradOffsetStride = wsGradOffsetStride;
    tilingDatafromBin->wsGradInputBaseElems = wsGradInputBaseElems;
    tilingDatafromBin->wsGradOffsetBaseElems = wsGradInputBaseElems;

    uint32_t numBlocks = needCoreNum;
    // 安全检查：numBlocks 不能超过 ascend950 最大核数 64
    ASSERT_LE(numBlocks, 64u);

    ICPU_SET_TILING_KEY(TILING_KEY_WITH_OFFSET);
    AscendC::SetKernelMode(KernelMode::AIV_MODE);

    ICPU_RUN_KF(deformable_roi_pool_grad<TILING_KEY_WITH_OFFSET>, numBlocks, grad, x, rois, offset, gradX, gradOffset,
                workspace, (uint8_t*)(tilingDatafromBin));

    // 写出输出
    std::string gradXOutFile = "./deformable_roi_pool_grad_data/float32_output_grad_x.bin";
    std::string gradOffsetOutFile = "./deformable_roi_pool_grad_data/float32_output_grad_offset.bin";
    WriteFile(gradXOutFile, gradX, gradXByteSize);
    WriteFile(gradOffsetOutFile, gradOffset, gradOffsetByteSize);

    // 释放资源
    AscendC::GmFree(grad);
    AscendC::GmFree(x);
    AscendC::GmFree(rois);
    AscendC::GmFree(offset);
    AscendC::GmFree(gradX);
    AscendC::GmFree(gradOffset);
    AscendC::GmFree(workspace);
    AscendC::GmFree(tiling);

    ASSERT_EQ(system("cd ./deformable_roi_pool_grad_data/ && python3 compare_data.py 'float32'"), 0);
}
