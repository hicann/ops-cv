    tiling->perCoreRois = static_cast<int32_t>(perCoreRois);
    tiling->numRois = static_cast<int32_t>(numRois);
    tiling->N = static_cast<int32_t>(N);
    tiling->C = static_cast<int32_t>(C);
    tiling->H = static_cast<int32_t>(H);
    tiling->W = static_cast<int32_t>(W);
    tiling->pooledHeight = static_cast<int32_t>(pooledH);
    tiling->pooledWidth = static_cast<int32_t>(pooledW);
    tiling->samplingRatio = static_cast<int32_t>(samplingRatio);
    tiling->spatialScale = static_cast<float>(spatialScale);
    tiling->gamma = static_cast<float>(gamma);

