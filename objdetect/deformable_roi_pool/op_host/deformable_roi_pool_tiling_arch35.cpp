static bool IsElementCountWithinLimit(std::initializer_list<int64_t> dims, int64_t limit, int64_t& elementCount)
{
    elementCount = 1;
    for (int64_t dim : dims) {
        if (dim == 0) {
            elementCount = 0;
            continue;
        }
        if (elementCount > limit / dim) {
            return false;
        }
        elementCount *= dim;
    }
    return true;
}

