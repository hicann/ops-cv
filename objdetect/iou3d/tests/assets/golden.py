# 常量（与 mmcv iou3d_cuda_kernel.cuh / iou3d.py 一致）
EPS_KERNEL = 1e-8  # 边相交退化判据阈值 (iou3d_cuda_kernel.cuh)
MARGIN = 1e-2  # 顶点包含测试绝对容差 (iou3d_cuda_kernel.cuh)
EPS_IOU = 1e-6  # IoU 分母 clamp 下限 (mmcv iou3d.py)


def _rotate_around_center(cx, cy, angle_cos, angle_sin, px, py):
    """绕中心点旋转（mmcv rotate_around_center）。
    x' = (px-cx)*cos - (py-cy)*sin + cx ; y' = (px-cx)*sin + (py-cy)*cos + cy。"""
    dx = px - cx
    dy = py - cy
    new_x = dx * angle_cos - dy * angle_sin + cx
    new_y = dx * angle_sin + dy * angle_cos + cy
    return new_x, new_y


def _get_box_corners(box):
    """轴对齐顶点 + 整体旋转（mmcv box_overlap）。顶点顺序 P0 左下→P1 右下→P2 右上→P3 左上。
    box = [x, y, z, w(dx), h(dy), d(dz), theta]。"""
    cx, cy = float(box[0]), float(box[1])
    dx, dy = float(box[3]), float(box[4])
    heading = float(box[6])
    dx_half, dy_half = dx / 2.0, dy / 2.0
    x1, y1 = cx - dx_half, cy - dy_half
    x2, y2 = cx + dx_half, cy + dy_half
    pts = [(x1, y1), (x2, y1), (x2, y2), (x1, y2)]  # 左下 右下 右上 左上
    angle_cos, angle_sin = math.cos(heading), math.sin(heading)
    return [
        _rotate_around_center(cx, cy, angle_cos, angle_sin, px, py) for px, py in pts
    ]


def _check_rect_cross(p0, p1, q0, q1):
    """AABB 快速排斥实验（mmcv check_rect_cross）。"""
    return (
        min(p0[0], p1[0]) <= max(q0[0], q1[0])
        and min(q0[0], q1[0]) <= max(p0[0], p1[0])
        and min(p0[1], p1[1]) <= max(q0[1], q1[1])
        and min(q0[1], q1[1]) <= max(p0[1], p1[1])
    )


def _cross_3pts(a, b, c):
    """叉积 (a-c) × (b-c)（mmcv cross）。"""
    return (a[0] - c[0]) * (b[1] - c[1]) - (b[0] - c[0]) * (a[1] - c[1])


def _intersection(p1, p0, q1, q0):
    """线段 P0P1 × Q0Q1 求交（mmcv intersection，参数序 p1,p0,q1,q0）。
    快速排斥 + 跨立实验（严格 >）+ |s5-s1|>EPS 叉积 / 否则一般式（不判 D==0）。返回 (x,y) 或 None。"""
    if not _check_rect_cross(p0, p1, q0, q1):
        return None
    s1 = _cross_3pts(q0, p1, p0)
    s2 = _cross_3pts(p1, q1, p0)
    s3 = _cross_3pts(p0, q1, q0)
    s4 = _cross_3pts(q1, p1, q0)
    if not (s1 * s2 > 0.0 and s3 * s4 > 0.0):
        return None
    s5 = _cross_3pts(q1, p1, p0)
    if abs(s5 - s1) > EPS_KERNEL:
        ans_x = (s5 * q0[0] - s1 * q1[0]) / (s5 - s1)
        ans_y = (s5 * q0[1] - s1 * q1[1]) / (s5 - s1)
    else:
        a0, b0 = p0[1] - p1[1], p1[0] - p0[0]
        c0 = p0[0] * p1[1] - p1[0] * p0[1]
        a1, b1 = q0[1] - q1[1], q1[0] - q0[0]
        c1 = q0[0] * q1[1] - q1[0] * q0[1]
        d = a0 * b1 - a1 * b0
        ans_x = (b0 * c1 - b1 * c0) / d
        ans_y = (a1 * c0 - a0 * c1) / d
    return (ans_x, ans_y)


def _check_in_box2d(box, p):
    """顶点包含测试 —— 反向旋转法 + MARGIN=1e-2（mmcv check_in_box2d）。
    把点 P 旋转 -heading 到框局部系，判 |rot_x|<dx/2+MARGIN && |rot_y|<dy/2+MARGIN（严格 <）。"""
    cx, cy = float(box[0]), float(box[1])
    dx, dy = float(box[3]), float(box[4])
    heading = float(box[6])
    angle_cos, angle_sin = math.cos(-heading), math.sin(-heading)
    dpx, dpy = p[0] - cx, p[1] - cy
    rot_x = dpx * angle_cos + dpy * (-angle_sin)
    rot_y = dpx * angle_sin + dpy * angle_cos
    return abs(rot_x) < dx / 2.0 + MARGIN and abs(rot_y) < dy / 2.0 + MARGIN


def _point_cmp(a, b, center):
    """极角比较：atan2(a-center) > atan2(b-center)（mmcv point_cmp）。"""
    return math.atan2(a[1] - center[1], a[0] - center[0]) > math.atan2(
        b[1] - center[1], b[0] - center[0]
    )


def _box_overlap(box_a, box_b):
    """BEV 重叠面积（mmcv box_overlap，逐行复刻）。16 组边交点 + 8 次顶点包含，
    质心=收集点均值，atan2 冒泡排序，扇形分解（以 p[0] 为基准），不去重。"""
    corners_a = _get_box_corners(box_a)
    corners_b = _get_box_corners(box_b)
    ca = corners_a + [corners_a[0]]  # 闭合
    cb = corners_b + [corners_b[0]]

    cross_points = []
    center = [0.0, 0.0]

    # 边相交（4×4=16）
    for i in range(4):
        for j in range(4):
            pt = _intersection(ca[i + 1], ca[i], cb[j + 1], cb[j])
            if pt is not None:
                cross_points.append(pt)
                center[0] += pt[0]
                center[1] += pt[1]
    # 顶点包含（8 次）
    for k in range(4):
        if _check_in_box2d(box_a, corners_b[k]):
            cross_points.append(corners_b[k])
            center[0] += corners_b[k][0]
            center[1] += corners_b[k][1]
        if _check_in_box2d(box_b, corners_a[k]):
            cross_points.append(corners_a[k])
            center[0] += corners_a[k][0]
            center[1] += corners_a[k][1]

    cnt = len(cross_points)
    if cnt == 0:
        return 0.0
    center[0] /= cnt
    center[1] /= cnt

    # 极角冒泡排序
    for j in range(cnt - 1):
        for i in range(cnt - j - 1):
            if _point_cmp(cross_points[i], cross_points[i + 1], center):
                cross_points[i], cross_points[i + 1] = (
                    cross_points[i + 1],
                    cross_points[i],
                )

    # 扇形分解（以 cross_points[0] 为基准）
    area = 0.0
    p0x, p0y = cross_points[0]
    for k in range(cnt - 1):
        ax, ay = cross_points[k][0] - p0x, cross_points[k][1] - p0y
        bx, by = cross_points[k + 1][0] - p0x, cross_points[k + 1][1] - p0y
        area += ax * by - ay * bx
    return abs(area) / 2.0


def _iou3d_pair(rect1, rect2):
    """单框对 3D IoU。rect = [x, y, z, w, h, d, theta]（float64 直算）。"""
    bev = _box_overlap(rect1, rect2)
    # Z 轴重叠高度：z ± d/2，clamp 非负
    z1_max, z1_min = rect1[2] + rect1[5] / 2.0, rect1[2] - rect1[5] / 2.0
    z2_max, z2_min = rect2[2] + rect2[5] / 2.0, rect2[2] - rect2[5] / 2.0
    overlaps_h = max(min(z1_max, z2_max) - max(z1_min, z2_min), 0.0)
    inter = bev * overlaps_h
    vol1 = rect1[3] * rect1[4] * rect1[5]
    vol2 = rect2[3] * rect2[4] * rect2[5]
    union = vol1 + vol2 - inter
    return inter / max(union, EPS_IOU)  # clamp（对标 mmcv，非加法 epsilon）


def iou3d_golden(bboxes, gtboxes, **kwargs):
    """3D 旋转框 IoU golden。

    bboxes [B,7,N], gtboxes [B,7,K] -> iou [B,N,K] (float32)。
    参数名/序对齐 op_host/iou3d_def.cpp（无 outputs）；空 Tensor（N==0 或 K==0）返回对应空形状。
    """
    b_np = np.asarray(bboxes, dtype=np.float64)
    g_np = np.asarray(gtboxes, dtype=np.float64)
    batch, dof, num_n = b_np.shape
    num_k = g_np.shape[2]
    iou = np.zeros((batch, num_n, num_k), dtype=np.float32)
    if num_n == 0 or num_k == 0:
        return iou  # 空 Tensor 短路
    for b in range(batch):
        for i in range(num_n):
            rect1 = [b_np[b, p, i] for p in range(7)]
            for j in range(num_k):
                rect2 = [g_np[b, p, j] for p in range(7)]
                iou[b, i, j] = np.float32(_iou3d_pair(rect1, rect2))
    return iou


