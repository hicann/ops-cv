static ge::graphStatus CalcUbSizing(gert::TilingContext* context, BoundingBoxEncodeTilingData* tiling, int64_t dim0,
                                    ge::DataType dataType, uint64_t ubSize, int64_t coreNum, int64_t* outCoreNum)
{
    int64_t elemBytes = (dataType == ge::DT_FLOAT16) ? BYTES_PER_FP16 : BYTES_PER_FP32;

    int64_t usedCoreNum = CeilDiv(dim0 * elemBytes * BITS_PER_BYTE, BLOCK_ELEM_THRESHOLD);
    if (usedCoreNum > coreNum)
        usedCoreNum = coreNum;
    if (usedCoreNum < 1)
        usedCoreNum = 1;

    int64_t blockFactor = CeilAlign(CeilDiv(dim0, usedCoreNum), ELEM_ALIGN_FACTOR);
    usedCoreNum = CeilDiv(dim0, blockFactor);

    // UB buffer sizing: anchor(T) + gt(T) + output(T) + calcBuf1(fp32) + calcBuf2(fp32)
    int64_t bufferDivisor;
    int64_t alignFactor;
    if (dataType == ge::DT_FLOAT16) {
        bufferDivisor = NUM_IO_BUFFERS * BYTES_PER_FP16 + NUM_CALC_BUFFERS * BYTES_PER_FP32;
        alignFactor = ONE_BLOCK_SIZE * BITS_PER_BYTE / FP16_BITS;
    } else {
        bufferDivisor = NUM_TOTAL_BUFFERS * BYTES_PER_FP32;
        alignFactor = ONE_BLOCK_SIZE * BITS_PER_BYTE / FP32_BITS;
    }

    // Reserve 64 bytes for means+stds tensors (4 floats each, 32-byte aligned)
    constexpr int64_t RESERVED_BYTES = 64;
    int64_t maxElemNum = (static_cast<int64_t>(ubSize) - RESERVED_BYTES) / bufferDivisor;
    constexpr int64_t MAX_DATACOPY_BLOCKLEN = 65535;
    int64_t maxElemByBlockLen = MAX_DATACOPY_BLOCKLEN / elemBytes;
    if (maxElemNum > maxElemByBlockLen) {
        maxElemNum = maxElemByBlockLen;
    }
    int64_t ubFactor = FloorAlign(maxElemNum, alignFactor);

    tiling->dim0 = dim0;
    tiling->blockFactor = blockFactor;
    tiling->ubFactor = ubFactor;
    *outCoreNum = usedCoreNum;
    return ge::GRAPH_SUCCESS;
}

