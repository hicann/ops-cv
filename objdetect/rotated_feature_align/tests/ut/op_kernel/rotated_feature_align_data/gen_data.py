SPATIAL_SCALE = 0.125


def parse_str_to_shape_list(shape_str):
    shape_str = shape_str.strip("(").strip(")")
    shape_list = [int(x) for x in shape_str.split(",")]
    return np.array(shape_list)


def bilinear_interpolate_golden(feat, yi, xi, height, width):
    """矢量化双线性插值（feat: (C,H,W)，yi/xi: (H,W)），边界三规则与 kernel 逐分支对齐。
    全程 float32 逐步舍入（对齐 kernel/torch golden 逐张量操作数值路径，防止
    float64 中间精度与 float32 kernel 在抵消场景下产生超 rtol 的系统性差异）
    """
    f32 = np.float32
    height_f = f32(height)
    width_f = f32(width)
    out = (yi < f32(-1.0)) | (yi > height_f) | (xi < f32(-1.0)) | (xi > width_f)
    yic = np.where(out, f32(0.0), yi)
    xic = np.where(out, f32(0.0), xi)
    yic = np.maximum(yic, f32(0.0))
    xic = np.maximum(xic, f32(0.0))
    y_low = np.floor(yic).astype(np.int64)
    x_low = np.floor(xic).astype(np.int64)
    over_y = y_low >= (height - 1)
    y_low = np.where(over_y, height - 1, y_low)
    y_high = np.where(over_y, y_low, y_low + 1)
    ly = np.where(over_y, f32(0.0), yic - y_low.astype(f32))
    over_x = x_low >= (width - 1)
    x_low = np.where(over_x, width - 1, x_low)
    x_high = np.where(over_x, x_low, x_low + 1)
    lx = np.where(over_x, f32(0.0), xic - x_low.astype(f32))
    hyw = f32(1.0) - ly
    hxw = f32(1.0) - lx
    v1 = feat[:, y_low, x_low]
    v2 = feat[:, y_low, x_high]
    v3 = feat[:, y_high, x_low]
    v4 = feat[:, y_high, x_high]
    interp = (hyw * hxw) * v1 + (hyw * lx) * v2 + (ly * hxw) * v3 + (ly * lx) * v4
    interp = np.where(out, f32(0.0), interp)
    return interp


def golden_rotated_feature_align(x, bboxes, spatial_scale, points):
    """Golden 计算（float32 逐步舍入，与 kernel 数值路径一致）
    累加顺序: 采样点 i 升序，逐项相加后累加原特征
    """
    if points not in (1, 5):
        raise ValueError(f"points must be 1 or 5, got {points}")
    f32 = np.float32
    scale = f32(spatial_scale)
    half = f32(0.5)
    _, _, height, width = x.shape
    num_n = x.shape[0]
    y = x.astype(np.float32).copy()
    for n in range(num_n):
        cy = bboxes[n, 0] * scale
        cx = bboxes[n, 1] * scale
        if points == 5:
            bw = bboxes[n, 2] * scale
            bh = bboxes[n, 3] * scale
            ang = bboxes[n, 4]
            w2 = bw * half
            h2 = bh * half
            cosa = np.cos(ang)
            sina = np.sin(ang)
            wx = cosa * w2
            wy = sina * w2
            hx = -sina * h2
            hy = cosa * h2
            px = np.stack(
                [cx, cx + wx + hx, cx - wx + hx, cx - wx - hx, cx + wx - hx], axis=0
            )
            py = np.stack(
                [cy, cy + wy + hy, cy - wy + hy, cy - wy - hy, cy + wy - hy], axis=0
            )
        else:
            px = cx[np.newaxis, :, :]
            py = cy[np.newaxis, :, :]
        feat = x[n]
        for i in range(points):
            interp = bilinear_interpolate_golden(feat, py[i], px[i], height, width)
            y[n] = y[n] + interp
    return y.astype(np.float32)


