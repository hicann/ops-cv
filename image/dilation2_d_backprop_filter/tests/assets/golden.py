# CALCULATED mode -- TF small operators (tf.Tensor in, tf.Tensor out)
#
# Boundary handling (matches kernel v2.3 simt.h lines 168-192):
#   hIn < 0  or hIn >= padInputH  ->  SKIP  (mask -inf, never wins argmax)
#   0 <= hIn < inputH, 0 <= wIn < inputW  ->  actual input value
#   inputH <= hIn < padInputH or inputW <= wIn < padInputW  ->  ZERO (value 0)
#
# The top/left padding is SKIP (not zero), while the bottom/right padding is
# ZERO.  This is the key difference from TF SAME (which zero-pads all sides).
# ============================================================================
def _tf_calculated_impl(x_tf, filter_tf, out_bp_tf, strides, rates, pads, ceil_mode):
    compute_dtype = x_tf.dtype
    stride_h, stride_w = strides[1], strides[2]
    rate_h, rate_w = rates[1], rates[2]
    batch, input_h, input_w, depth = x_tf.shape
    filter_h, filter_w, _ = filter_tf.shape

    pad_top, pad_bottom, pad_left, pad_right = pads
    pad_input_h = input_h + pad_top + pad_bottom
    pad_input_w = input_w + pad_left + pad_right

    out_h = out_bp_tf.shape[1]
    out_w = out_bp_tf.shape[2]

    # --- Step 1: build index tensors ---
    # h_in[out_h, filter_h] = h_out * stride_h - pad_top + fh * rate_h
    h_out_range = tf.range(out_h, dtype=tf.int32)
    fh_range = tf.range(filter_h, dtype=tf.int32)
    h_in_2d = h_out_range[:, None] * stride_h - pad_top + fh_range[None, :] * rate_h

    w_out_range = tf.range(out_w, dtype=tf.int32)
    fw_range = tf.range(filter_w, dtype=tf.int32)
    w_in_2d = w_out_range[:, None] * stride_w - pad_left + fw_range[None, :] * rate_w

    # Broadcast to (batch, out_h, out_w, depth, filter_h, filter_w)
    shape6 = [batch, out_h, out_w, depth, filter_h, filter_w]
    h_in_full = tf.broadcast_to(h_in_2d[None, :, None, None, :, None], shape6)
    w_in_full = tf.broadcast_to(w_in_2d[None, None, :, None, None, :], shape6)

    # --- Step 2: masks (using original indices, before clamping) ---
    # in_bounds: 0 <= h_in < pad_input_h AND 0 <= w_in < pad_input_w
    in_bounds = tf.logical_and(
        tf.logical_and(h_in_full >= 0, h_in_full < pad_input_h),
        tf.logical_and(w_in_full >= 0, w_in_full < pad_input_w),
    )
    # in_input: 0 <= h_in < input_h AND 0 <= w_in < input_w
    in_input = tf.logical_and(
        tf.logical_and(h_in_full >= 0, h_in_full < input_h),
        tf.logical_and(w_in_full >= 0, w_in_full < input_w),
    )

    # --- Step 3: gather input values at clamped indices ---
    h_in_clamped = tf.clip_by_value(h_in_full, 0, input_h - 1)
    w_in_clamped = tf.clip_by_value(w_in_full, 0, input_w - 1)

    b_idx = tf.broadcast_to(
        tf.range(batch, dtype=tf.int32)[:, None, None, None, None, None], shape6
    )
    d_idx = tf.broadcast_to(
        tf.range(depth, dtype=tf.int32)[None, None, None, :, None, None], shape6
    )

    gather_idx = tf.stack([b_idx, h_in_clamped, w_in_clamped, d_idx], axis=-1)
    x_vals = tf.gather_nd(x_tf, gather_idx)  # (batch, out_h, out_w, depth, fh, fw)

    # Zero out positions outside original input (bottom/right zero-padding)
    x_vals = x_vals * tf.cast(in_input, compute_dtype)

    # --- Step 4: add filter ---
    # filter (fh, fw, depth) -> (depth, fh, fw) -> broadcast
    filter_exp = tf.transpose(filter_tf, [2, 0, 1])[None, None, None, :, :, :]
    filter_exp = tf.broadcast_to(filter_exp, shape6)

    vals = x_vals + filter_exp

    # --- Step 5: mask out-of-bounds with -inf (skip) ---
    neg_inf = tf.constant(float("-inf"), dtype=compute_dtype)
    vals = tf.where(in_bounds, vals, tf.fill(tf.shape(vals), neg_inf))

    # --- Step 6: argmax over (filter_h, filter_w) ---
    vals_flat = tf.reshape(vals, [batch, out_h, out_w, depth, filter_h * filter_w])
    argmax_flat = tf.argmax(vals_flat, axis=-1, output_type=tf.int32)

    fh_max = argmax_flat // filter_w
    fw_max = argmax_flat % filter_w

    # --- Step 7: scatter-add out_backprop to filter positions ---
    d_full = tf.broadcast_to(
        tf.range(depth, dtype=tf.int32)[None, None, None, :],
        [batch, out_h, out_w, depth],
    )
    filter_idx = fh_max * filter_w * depth + fw_max * depth + d_full

    out_bp_flat = tf.reshape(out_bp_tf, [-1])
    filter_idx_flat = tf.reshape(filter_idx, [-1])

    filter_size = filter_h * filter_w * depth
    filter_bp_flat = tf.math.unsorted_segment_sum(
        data=out_bp_flat, segment_ids=filter_idx_flat, num_segments=filter_size
    )

    return tf.reshape(filter_bp_flat, [filter_h, filter_w, depth])


