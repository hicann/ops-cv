static Tensor MakeFloatTensor(const vector<int64_t>& shape, const vector<float>& data)
{
    TensorDesc desc(ge::Shape(shape), FORMAT_ND, DT_FLOAT);
    desc.SetPlacement(ge::kPlacementHost);
    desc.SetFormat(FORMAT_ND);
    desc.SetRealDimCnt(shape.size());
    Tensor tensor(desc);
    tensor.SetData(reinterpret_cast<const uint8_t*>(data.data()), data.size() * sizeof(float));
    return tensor;
}

static vector<float> MakeIdentityLut(int64_t lutN)
{
    vector<float> lut;
    lut.reserve(static_cast<size_t>(lutN * lutN * lutN * 3));
    const float step = 255.0f / static_cast<float>(lutN - 1);
    for (int64_t b = 0; b < lutN; ++b) {
        for (int64_t g = 0; g < lutN; ++g) {
            for (int64_t r = 0; r < lutN; ++r) {
                lut.push_back(static_cast<float>(b) * step);
                lut.push_back(static_cast<float>(g) * step);
                lut.push_back(static_cast<float>(r) * step);
            }
        }
    }
    return lut;
}

static bool CheckOutput(const Tensor& output, const vector<float>& expected)
{
    if (output.GetSize() != expected.size() * sizeof(float) || output.GetData() == nullptr) {
        return false;
    }
    const float* actual = reinterpret_cast<const float*>(output.GetData());
    for (size_t i = 0; i < expected.size(); ++i) {
        printf("  output[%zu] = %.6f, expected = %.6f\n", i, actual[i], expected[i]);
        if (std::fabs(actual[i] - expected[i]) > 1e-4f) {
            return false;
        }
    }
    return true;
}

int main()
{
    const vector<int64_t> imgShape = {1, 2, 2, 3};
    const vector<int64_t> lutShape = {2, 2, 2, 3};
    const vector<float> imgData = {
        0.0f, 0.0f, 0.0f, 255.0f, 0.0f, 0.0f, 0.0f, 255.0f, 0.0f, 255.0f, 255.0f, 255.0f,
    };
    const vector<float> lutData = MakeIdentityLut(2);

    printf("%s - INFO - [GEIR]: Initialize GE\n", GetTime().c_str());
    std::map<AscendString, AscendString> globalOptions = {
        {"ge.exec.deviceId", "0"},
        {"ge.graphRunMode", "1"},
    };
    Status ret = ge::GEInitialize(globalOptions);
    if (ret != SUCCESS) {
        printf("%s - ERROR - [GEIR]: GEInitialize failed\n", GetTime().c_str());
        return FAILED;
    }

    Graph graph("lut3_d_geir_graph");
    auto img = op::Data("img").set_attr_index(0);
    TensorDesc imgDesc(ge::Shape(imgShape), FORMAT_ND, DT_FLOAT);
    imgDesc.SetPlacement(ge::kPlacementHost);
    img.update_input_desc_x(imgDesc);

    auto lutTable = op::Data("lut_table").set_attr_index(1);
    TensorDesc lutDesc(ge::Shape(lutShape), FORMAT_ND, DT_FLOAT);
    lutDesc.SetPlacement(ge::kPlacementHost);
    lutTable.update_input_desc_x(lutDesc);

    auto lut3D = op::LUT3D("lut3_d");
    lut3D.set_input_img(img);
    lut3D.set_input_lut_table(lutTable);
    lut3D.update_input_desc_img(imgDesc);
    lut3D.update_input_desc_lut_table(lutDesc);
    TensorDesc outputDesc(ge::Shape(imgShape), FORMAT_ND, DT_FLOAT);
    lut3D.update_output_desc_lut_img(outputDesc);

    graph.SetInputs({img, lutTable}).SetOutputs({lut3D});

    std::map<AscendString, AscendString> buildOptions;
    ge::Session* session = new Session(buildOptions);
    if (session == nullptr) {
        printf("%s - ERROR - [GEIR]: Create Session failed\n", GetTime().c_str());
        ge::GEFinalize();
        return FAILED;
    }

    constexpr uint32_t graphId = 0;
    std::map<AscendString, AscendString> graphOptions;
    ret = session->AddGraph(graphId, graph, graphOptions);
    if (ret != SUCCESS) {
        printf("%s - ERROR - [GEIR]: AddGraph failed: %s\n", GetTime().c_str(), ge::GEGetErrorMsgV2().GetString());
        delete session;
        ge::GEFinalize();
        return FAILED;
    }

    vector<Tensor> inputs = {MakeFloatTensor(imgShape, imgData), MakeFloatTensor(lutShape, lutData)};
    vector<Tensor> outputs;
    printf("%s - INFO - [GEIR]: RunGraph\n", GetTime().c_str());
    ret = session->RunGraph(graphId, inputs, outputs);
    if (ret != SUCCESS) {
        printf("%s - ERROR - [GEIR]: RunGraph failed: %s\n", GetTime().c_str(), ge::GEGetErrorMsgV2().GetString());
        delete session;
        ge::GEFinalize();
        return FAILED;
    }

    bool passed = outputs.size() == 1 && CheckOutput(outputs[0], imgData);
    printf("%s - INFO - [GEIR]: LUT3D graph-mode example %s\n", GetTime().c_str(), passed ? "PASSED" : "FAILED");

    delete session;
    ret = ge::GEFinalize();
    if (ret != SUCCESS) {
        printf("%s - ERROR - [GEIR]: GEFinalize failed\n", GetTime().c_str());
        return FAILED;
    }
    return passed ? SUCCESS : FAILED;
}
