def parse_str_to_shape_list(shape_str):
    shape_str = shape_str.strip("(").strip(")")
    shape_list = [int(x) for x in shape_str.split(",")]
    return np.array(shape_list)


def _cubic_conv1(x, a=-0.75):
    return ((a + 2.0) * x - (a + 3.0)) * x * x + 1.0


def _cubic_conv2(x, a=-0.75):
    return ((a * x - 5.0 * a) * x + 8.0 * a) * x - 4.0 * a


def _cubic_coeffs(t, a=-0.75):
    return [
        _cubic_conv2(t + 1.0, a),
        _cubic_conv1(t, a),
        _cubic_conv1(1.0 - t, a),
        _cubic_conv2(2.0 - t, a),
    ]


def _scale(in_size, out_size, align_corners):
    if align_corners:
        return (in_size - 1.0) / (out_size - 1.0) if out_size > 1 else 0.0
    return float(in_size) / float(out_size) if out_size > 0 else 0.0


def _src_idx(scale, dst, align_corners, clamp_neg):
    if align_corners:
        return scale * float(dst)
    v = scale * (float(dst) + 0.5) - 0.5
    return max(v, 0.0) if clamp_neg else v


